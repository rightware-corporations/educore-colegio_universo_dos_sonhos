import assert from "node:assert/strict";
import { mkdirSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { chromium } from "playwright";
const base=process.env.COLUS_PORTAL_URL??"http://127.0.0.1:4174";
const dir=resolve("qa-artifacts/browser");
mkdirSync(dir,{recursive:true});
const browser=await chromium.launch({headless:true,args:["--no-sandbox"]});
const errors=[];
const records=[];
async function enter(page,label){
 await page.locator('header button[aria-label="Trocar perfil"]').click();
 await page.getByRole("button",{name:new RegExp("^"+label+"$")}).click();
 await page.getByRole("button",{name:new RegExp("Entrar como "+label)}).click();
}
try{
 const page=await browser.newPage({viewport:{width:1440,height:900},reducedMotion:"no-preference"});
 page.on("pageerror",e=>errors.push(e.message));
 await page.goto(base+"/welcome",{waitUntil:"networkidle"});
 assert.equal(await page.locator('img[alt="Comunidade escolar COLUS"]').count(),1,"Welcome must use official COLUS scene");
 await page.waitForTimeout(900); // allow approved intro and route animations to settle
 await page.screenshot({path:resolve(dir,"welcome-desktop.png"),fullPage:true});
 await page.getByRole("link",{name:/Explorar o portal/}).click();
 assert.match(page.url(),/\/login$/);
 await page.screenshot({path:resolve(dir,"login-desktop.png"),fullPage:true});
 await page.getByRole("button",{name:"Professor"}).click();
 await page.getByRole("button",{name:/Entrar como Professor/}).click();
 assert.match(page.url(),/\/app\/teacher\/dashboard$/);
 assert.equal(await page.getByRole("button",{name:/Registar falta/}).count(),1);
 await page.waitForTimeout(900); // allow approved intro and route animations to settle
 await page.screenshot({path:resolve(dir,"professor-dashboard.png"),fullPage:true});
 await page.getByRole("button",{name:/Registar falta/}).click();
 assert.ok((await page.locator("main").innerText()).includes("Falta registada"));
 records.push({step:"teacher register absence",status:"pass"});
 await enter(page,"Encarregado");
 assert.match(page.url(),/\/app\/guardian\/dashboard$/);
 assert.ok((await page.locator("main").innerText()).includes("Falta registada"),"Guardian must see teacher absence");
 await page.waitForTimeout(900); // allow approved intro and route animations to settle
 await page.screenshot({path:resolve(dir,"encarregado-after-absence.png"),fullPage:true});
 records.push({step:"guardian cross-role attendance",status:"pass"});
 await enter(page,"Finanças");
 await page.getByRole("button",{name:/Validar pagamento/}).click();
 assert.ok((await page.locator("main").innerText()).includes("Pagamento validado"));
 records.push({step:"finance validate payment",status:"pass"});
 await enter(page,"Encarregado");
 assert.ok((await page.locator("main").innerText()).includes("Validado"),"Guardian must see finance validation");
 await page.reload({waitUntil:"networkidle"});
 assert.match(page.url(),/\/app\/guardian\/dashboard$/);
 assert.ok((await page.locator("main").innerText()).includes("Validado"),"Demo state should survive same-tab reload");
 await page.waitForTimeout(900); // allow approved intro and route animations to settle
 await page.screenshot({path:resolve(dir,"encarregado-after-payment.png"),fullPage:true});
 records.push({step:"guardian cross-role payment and refresh",status:"pass"});
 await enter(page,"Secretaria");
 await page.goto(base+"/app/secretary/students",{waitUntil:"networkidle"});
 await page.getByRole("button",{name:/Novo aluno/}).click();
 await page.getByRole("textbox",{name:"Nome completo"}).fill("Íris Sumbana");
 await page.getByRole("combobox",{name:"Classe pretendida"}).selectOption("9");
 await page.getByRole("button",{name:"Guardar",exact:true}).click();
 assert.equal(await page.locator("table").getByText("Íris Sumbana", {exact:true}).count(),1,"Secretary student registration");
 await page.getByRole("button",{name:"Editar Íris Sumbana"}).click();
 await page.getByRole("textbox",{name:"Nome completo"}).fill("Íris Sumbana Matola");
 await page.getByRole("button",{name:"Guardar",exact:true}).click();
 assert.equal(await page.locator("table").getByText("Íris Sumbana Matola",{exact:true}).count(),1,"Secretary edit");
 records.push({step:"secretary create and edit student",status:"pass"});
 await enter(page,"Pedagogia");
 await page.goto(base+"/app/pedagogy/assignments",{waitUntil:"networkidle"});
 await page.getByRole("combobox",{name:"Atribuir turma a Íris Sumbana Matola"}).selectOption("CL-09-A");
 await page.reload({waitUntil:"networkidle"});
 await enter(page,"Secretaria");
 await page.goto(base+"/app/secretary/students",{waitUntil:"networkidle"});
 assert.ok((await page.locator("main").innerText()).includes("Íris Sumbana Matola"),"School enrolment persists across roles");
 await page.once("dialog",dialog=>dialog.accept());
 await page.getByRole("button",{name:"Arquivar Íris Sumbana Matola"}).click();
 assert.equal(await page.locator("table").getByText("Íris Sumbana Matola",{exact:true}).count(),0,"Archived student excluded from active registry");
 await page.getByRole("checkbox",{name:/Mostrar arquivados/}).check();
 assert.equal(await page.locator("table").getByText("Íris Sumbana Matola",{exact:true}).count(),1,"Archived record remains accessible");
 records.push({step:"pedagogy assign class and secretary archive with history",status:"pass"});
 await enter(page,"Pedagogia");
 await page.goto(base+"/app/pedagogy/classes",{waitUntil:"networkidle"});
 assert.ok((await page.locator("main").innerText()).includes("Mapa de turmas"),"Classes must be distinct from assignments");
 await page.getByRole("button",{name:/Nova turma/}).click();
 await page.getByRole("combobox",{name:"Nova classe"}).selectOption("8");
 await page.getByRole("combobox",{name:"Letra da turma"}).selectOption("A");
 await page.getByRole("spinbutton",{name:"Lotação da nova turma"}).fill("28");
 await page.getByRole("button",{name:"Criar",exact:true}).click();
 assert.ok((await page.locator("main").innerText()).includes("8ª A"),"Pedagogy must create an active class");
 await page.waitForTimeout(600);
 await page.screenshot({path:resolve(dir,"pedagogia-classes-v3.png"),fullPage:true});
 records.push({step:"distinct class management and create class",status:"pass"});
 await page.goto(base+"/app/pedagogy/staff",{waitUntil:"networkidle"});
 await page.getByRole("button",{name:/Registar professor/}).click();
 await page.getByRole("textbox",{name:"Nome do professor"}).fill("Hélio Macuácua");
 await page.getByRole("combobox",{name:"Disciplina do professor"}).selectOption({label:"Matemática"});
 await page.getByRole("button",{name:/Guardar professor/}).click();
 assert.ok((await page.locator("main").innerText()).includes("Hélio Macuácua"));
 await page.screenshot({path:resolve(dir,"pedagogia-docentes-v3.png"),fullPage:true});
 await page.goto(base+"/app/pedagogy/assignments",{waitUntil:"networkidle"});
 await page.getByRole("button",{name:/8ª A/}).click();
 await page.getByRole("button",{name:"Atribuir Hélio Macuácua"}).click();
 assert.ok((await page.locator("main").innerText()).includes("Atribuído"));
 await page.screenshot({path:resolve(dir,"pedagogia-atribuicoes-v3.png"),fullPage:true});
 records.push({step:"teacher CRUD and class assignment",status:"pass"});
 await page.goto(base+"/app/pedagogy/timetable",{waitUntil:"networkidle"});
 await page.getByRole("combobox",{name:"Filtrar horário por turma"}).selectOption("CL-08-A");
 await page.getByRole("button",{name:/Adicionar aula/}).click();
 await page.getByRole("combobox",{name:"Professor da aula"}).selectOption({label:"Hélio Macuácua · Matemática"});
 await page.getByRole("combobox",{name:"Dia da aula"}).selectOption("2");
 await page.getByRole("textbox",{name:"Sala"}).fill("SALA-8A");
 await page.getByRole("button",{name:/Guardar aula/}).click();
 assert.ok((await page.locator("main").innerText()).includes("Hélio Macuácua"),"Weekly timetable must read stored lessons");
 await page.waitForTimeout(600);
 await page.screenshot({path:resolve(dir,"pedagogia-horario-v3.png"),fullPage:true});
 await page.getByRole("button",{name:/Adicionar aula/}).click();
 await page.getByRole("combobox",{name:"Professor da aula"}).selectOption({label:"Hélio Macuácua · Matemática"});
 await page.getByRole("combobox",{name:"Dia da aula"}).selectOption("2");
 await page.getByRole("textbox",{name:"Sala"}).fill("SALA-8A");
 await page.getByRole("button",{name:/Guardar aula/}).click();
 assert.ok((await page.getByRole("alert").innerText()).includes("Conflito de horário"));
 records.push({step:"weekly lesson scheduling and collision prevention",status:"pass"});
 await page.goto(base+"/app/pedagogy/grades",{waitUntil:"networkidle"});
 assert.ok((await page.locator("main").innerText()).includes("Gestão de avaliações"));
 await page.screenshot({path:resolve(dir,"pedagogia-avaliacoes-v3.png"),fullPage:true});
 await page.goto(base+"/app/pedagogy/attendance",{waitUntil:"networkidle"});
 assert.ok((await page.locator("main").innerText()).includes("Controlo de assiduidade"));
 await page.screenshot({path:resolve(dir,"pedagogia-assiduidade-v3.png"),fullPage:true});
 records.push({step:"distinct academic monitoring workspaces",status:"pass"});
 await page.setViewportSize({width:390,height:844});
 await page.goto(base+"/welcome",{waitUntil:"networkidle"});
 const overflow=await page.evaluate(()=>document.documentElement.scrollWidth-window.innerWidth);
 assert.ok(overflow<=3,"Welcome mobile horizontal overflow "+overflow);
 await page.waitForTimeout(900); // allow approved intro and route animations to settle
 await page.screenshot({path:resolve(dir,"welcome-mobile.png"),fullPage:true});
 await page.goto(base+"/login",{waitUntil:"networkidle"});
 await page.screenshot({path:resolve(dir,"login-mobile.png"),fullPage:true});
 await page.getByRole("button",{name:"Aluno"}).click();
 await page.getByRole("button",{name:/Entrar como Aluno/}).click();
 const appOverflow=await page.evaluate(()=>document.documentElement.scrollWidth-window.innerWidth);
 assert.ok(appOverflow<=3,"App mobile horizontal overflow "+appOverflow);
 await page.waitForTimeout(900); // allow approved intro and route animations to settle
 await page.screenshot({path:resolve(dir,"aluno-mobile.png"),fullPage:true});
 const studentText=(await page.locator("main").innerText()).toLocaleLowerCase();
 assert.ok(!/propina|pagamento|finan[cç]/i.test(studentText),"Student must never see finance or payment info");
 await page.goto(base+"/app/student/payments",{waitUntil:"networkidle"});
 assert.match(page.url(),/\/app\/student\/dashboard$/,"Student finance route must be denied");
 records.push({step:"student financial modules and deep link excluded",status:"pass"});
 records.push({step:"mobile 390px welcome login dashboard",status:"pass",overflow,appOverflow});
 await page.goto(base+"/",{waitUntil:"domcontentloaded"});
 assert.equal(await page.locator('img[alt="COLUS"]').count(),1,"Independent splash required");
 await page.screenshot({path:resolve(dir,"splash-desktop.png")});
 records.push({step:"independent splash entry",status:"pass"});
 assert.deepEqual(errors,[],"Runtime browser exceptions");
 writeFileSync(resolve(dir,"results.json"),JSON.stringify({status:"pass",records,errors},null,2));
 console.log("COLUS PORTAL BROWSER QA PASS",JSON.stringify(records));
 await page.close();
}catch(e){writeFileSync(resolve(dir,"results.json"),JSON.stringify({status:"fail",records,errors,error:String(e)},null,2));throw e;}
finally{await browser.close();}
